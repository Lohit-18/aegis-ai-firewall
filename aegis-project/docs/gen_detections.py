"""Generate docs/detections.md from the rule tables.

Hand-written rule documentation drifts the moment someone edits a weight. This
reads the actual objects the engine loads, so the document cannot be wrong.

Run: python docs/gen_detections.py
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from aegis.detect.egress import EGRESS_PATTERNS  # noqa: E402
from aegis.detect.signatures import RULES  # noqa: E402

PREFIX_NAMES = {
    "AEG-OVR": "Instruction override",
    "AEG-ROL": "Role manipulation",
    "AEG-EXF": "System-prompt extraction",
    "AEG-DLM": "Delimiter and role-token smuggling",
    "AEG-AUT": "False authority and social engineering",
    "AEG-OUT": "Exfiltration instructions",
    "AEG-TOO": "Tool and agent abuse",
    "AEG-ENC": "Encoding instructions",
    "AEG-FMT": "Output-format hijack",
}

STRUCTURAL = [
    ("AEG-STR-001", "0.28–0.45", "medium", "Zero-width characters, scored by density"),
    ("AEG-STR-002", "0.88", "critical", "Instructions hidden in Unicode tag characters (U+E0000)"),
    ("AEG-STR-003", "0.62", "high", "Bidirectional override characters"),
    ("AEG-STR-004", "0.30–0.60", "medium", "Words mixing characters from multiple scripts"),
    ("AEG-STR-005", "0.34", "low", "Excessive combining marks"),
    ("AEG-STR-006", "0.30", "low", "Newline padding to flush earlier context"),
    ("AEG-STR-010", "≤0.94", "critical", "Encoded blob decodes to injection content"),
    ("AEG-STR-011", "0.20", "low", "Large encoded blob decoding to readable text"),
]

def main() -> None:
    out: list[str] = []
    w = out.append

    w("# Detection reference")
    w("")
    w("*Generated by `docs/gen_detections.py` — do not edit by hand.*")
    w("")
    w(f"{len(RULES)} signature rules · {len(STRUCTURAL)} structural detectors · "
      f"{len(EGRESS_PATTERNS) + 3} egress detectors")
    w("")
    w("## Reading the columns")
    w("")
    w("**Weight** answers *if this were the only evidence, how confident would I "
      "be?* It is never 1.0 — every pattern here has a benign counterexample.")
    w("")
    w("**Severity** answers a different question: *how damaging is this if the "
      "signal is right?* A rule can be confident about something minor, or "
      "tentative about something catastrophic. Conflating the two axes is a "
      "mistake this project made once and had to undo.")
    w("")
    w("**Channels** lists where the rule applies. Rules restricted to `tool` and "
      "`document` describe behaviour with no legitimate reason to appear in "
      "untrusted content at all.")
    w("")
    w("**Boost** is the multiplier applied in untrusted channels.")
    w("")

    groups: dict[str, list] = defaultdict(list)
    for rule in RULES:
        groups[rule.id.rsplit("-", 1)[0]].append(rule)

    w("## Signature rules")
    for prefix in sorted(groups, key=lambda p: PREFIX_NAMES.get(p, p)):
        w("")
        w(f"### {PREFIX_NAMES.get(prefix, prefix)}")
        w("")
        w("| ID | Weight | Severity | Boost | Channels | Description |")
        w("|---|---:|---|---:|---|---|")
        for rule in sorted(groups[prefix], key=lambda r: r.id):
            channels = ", ".join(sorted(c.value for c in rule.channels))
            boost = f"×{rule.untrusted_boost:g}" if rule.untrusted_boost != 1.0 else "—"
            w(f"| `{rule.id}` | {rule.weight:.2f} | {rule.severity.value} | {boost} "
              f"| {channels} | {rule.message} |")

    w("")
    w("## Structural detectors")
    w("")
    w("These score *how* text is constructed rather than what it says. Obfuscation "
      "is itself evidence: nobody accidentally writes a sentence containing "
      "seventeen zero-width joiners.")
    w("")
    w("| ID | Weight | Severity | Description |")
    w("|---|---:|---|---|")
    for rid, weight, sev, desc in STRUCTURAL:
        w(f"| `{rid}` | {weight} | {sev} | {desc} |")

    w("")
    w("## Egress detectors")
    w("")
    w("Applied to model output, buffered or streamed. `AEG-EGR-001` is the only "
      "detector in the system with no false-positive mode: the canary token "
      "exists nowhere else, so its presence is proof rather than evidence.")
    w("")
    w("| ID | Weight | Severity | Description |")
    w("|---|---:|---|---|")
    w("| `AEG-EGR-001` | 0.99 | critical | System-prompt canary present in output |")
    for rule in EGRESS_PATTERNS:
        w(f"| `{rule.id}` | {rule.weight:.2f} | {rule.severity.value} | {rule.message} |")
    w("| `AEG-EGR-020` | 0.86 | critical | Markdown image to non-allowlisted host carrying a payload |")
    w("| `AEG-EGR-021` | 0.44 | medium | Markdown link to non-allowlisted host carrying a payload |")

    w("")
    w("## Mitigations")
    w("")
    w("| ID | Effect | Description |")
    w("|---|---|---|")
    w("| `AEG-MIT-001` | damping | Use/mention damping — quotation, attribution, "
      "meta-discourse and interrogative framing reduce the score. Capped at 80% "
      "in the user channel and 30% in untrusted channels, because quoting is "
      "itself an evasion technique. |")
    w("")

    path = Path(__file__).parent / "detections.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(RULES)} signature rules)")


if __name__ == "__main__":
    main()
